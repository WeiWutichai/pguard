//! Repository layer — the ONLY place that touches the `identity` schema.
//!
//! Runtime `sqlx::query`/`query_as` (not the compile-time `query!` macro): the scaffold
//! has no DATABASE_URL / offline `.sqlx` cache at build time. Argon2 work (CPU-bound) is
//! offloaded to `spawn_blocking` here — the scheduling is an I/O concern, so it lives in
//! `repo`, while the pure hash/verify functions stay in `domain::password`.

use std::sync::LazyLock;

use chrono::{DateTime, TimeDelta, Utc};
use sqlx::PgPool;
use uuid::Uuid;

use shared::error::AppError;

use crate::domain::rotation::StoredRefresh;
use crate::domain::{password, revocation};
use crate::models::AuthUserRow;

/// Refresh-token lifetime (RFC 6749 §6 rotation; 7 days mirrors v1).
const REFRESH_TOKEN_DAYS: i64 = 7;

/// A real Argon2id hash of a throwaway value, computed once at first use. Verified against
/// on the no-such-user / inactive path so login takes ~the same time whether or not the
/// account exists (anti-enumeration; ported from v1 auth `service.rs`). Generated by our
/// own hasher, so it is ALWAYS a valid PHC string — the no-user path can never 500 on a
/// hash-parse error (a hand-written constant could).
static DUMMY_HASH: LazyLock<String> =
    LazyLock::new(|| password::hash_secret("pguard-anti-enumeration-dummy").expect("dummy hash"));

/// Row returned by the login lookup (password hash stays inside repo).
struct UserAuthRow {
    id: Uuid,
    role: String,
    password_hash: String,
    is_active: bool,
    /// Account approval state (`pending`/`approved`/`rejected`). Login is allowed ONLY
    /// when `approved` — a registered-but-unapproved account cannot authenticate.
    approval_status: String,
    token_revocation_version: i32,
}

/// Look up a user by phone OR email. Returns `None` if absent (inactive users still
/// return so the caller can run the dummy-verify path uniformly).
async fn find_user_by_identifier(
    db: &PgPool,
    identifier: &str,
) -> Result<Option<UserAuthRow>, AppError> {
    let row: Option<(Uuid, String, String, bool, String, i32)> = sqlx::query_as(
        r#"
        SELECT id, role::text AS role, password_hash, is_active,
               approval_status::text AS approval_status, token_revocation_version
        FROM identity.users
        WHERE phone = $1 OR email = $1
        "#,
    )
    .bind(identifier)
    .fetch_optional(db)
    .await?;

    Ok(row.map(
        |(id, role, password_hash, is_active, approval_status, trv)| UserAuthRow {
            id,
            role,
            password_hash,
            is_active,
            approval_status,
            token_revocation_version: trv,
        },
    ))
}

/// Verify credentials. Always returns a generic `Unauthorized` on any failure (no
/// user-enumeration); runs the Argon2 verify even when the user is missing/ineligible so
/// timing does not leak existence OR approval state. Returns the minimal user identity on
/// success. ELIGIBILITY = active AND `approval_status = 'approved'`: a pending/rejected
/// account is rejected with the SAME generic 401 as a wrong password (so login cannot be
/// used to probe whether a phone is registered-but-pending).
pub async fn verify_credentials(
    db: &PgPool,
    identifier: &str,
    password: &str,
) -> Result<AuthUserRow, AppError> {
    let user = find_user_by_identifier(db, identifier).await?;

    // Pick the hash to verify against: the real one (only for an eligible account), or a
    // constant dummy. Either way we spend the same Argon2 time.
    let (hash, eligible, identity) = match &user {
        Some(u) if u.is_active && u.approval_status == "approved" => (
            u.password_hash.clone(),
            true,
            Some(AuthUserRow {
                id: u.id,
                role: u.role.clone(),
                token_revocation_version: u.token_revocation_version,
            }),
        ),
        _ => (DUMMY_HASH.to_string(), false, None),
    };

    let password = password.to_string();
    let ok = tokio::task::spawn_blocking(move || password::verify_secret(&password, &hash))
        .await
        .map_err(|e| AppError::Internal(format!("verify task failed: {e}")))??;

    match (ok, eligible, identity) {
        (true, true, Some(id)) => Ok(id),
        _ => Err(AppError::Unauthorized("Invalid credentials".to_string())),
    }
}

/// UPSERT a freshly-registered account in the `pending` (non-loginable) state and return
/// its `user_id`. The PIN-hash supplied by the client (SHA-256 hex of the PIN) is Argon2'd
/// here (CPU-bound → `spawn_blocking`) and stored as the password hash.
///
/// `ON CONFLICT (phone)`: re-registering a phone that is STILL pending is allowed — it
/// refreshes the credentials/role and keeps the account pending (a user who never finished
/// onboarding can start over). A phone that already exists in a NON-pending state
/// (approved/rejected) makes the `WHERE approval_status = 'pending'` predicate false, so the
/// row is NOT touched and `RETURNING` yields no row → `Conflict` ("log in instead"). This is
/// the only place identity creates a user; profile/otp never write this schema.
// `skip(db, phone, pin_hash)`: never log the phone (PII) or the pin hash; `role` is fine.
#[tracing::instrument(skip(db, phone, pin_hash))]
pub async fn upsert_pending_user(
    db: &PgPool,
    phone: &str,
    role: &str,
    pin_hash: &str,
) -> Result<Uuid, AppError> {
    let pin_hash = pin_hash.to_string();
    let password_hash = tokio::task::spawn_blocking(move || password::hash_secret(&pin_hash))
        .await
        .map_err(|e| AppError::Internal(format!("hash task failed: {e}")))??;

    let row: Option<(Uuid,)> = sqlx::query_as(
        r#"
        INSERT INTO identity.users (phone, password_hash, role, approval_status)
        VALUES ($1, $2, $3::identity.user_role, 'pending'::identity.approval_status)
        ON CONFLICT (phone) DO UPDATE
          SET password_hash   = EXCLUDED.password_hash,
              role            = EXCLUDED.role,
              approval_status = 'pending'::identity.approval_status,
              updated_at      = now()
          WHERE identity.users.approval_status = 'pending'::identity.approval_status
        RETURNING id
        "#,
    )
    .bind(phone)
    .bind(&password_hash)
    .bind(role)
    .fetch_optional(db)
    .await?;

    row.map(|(id,)| id).ok_or_else(|| {
        AppError::Conflict(
            "This phone number is already registered. Please log in instead.".to_string(),
        )
    })
}

/// Switch a PENDING account's role (the onboarding "pick another role" path). Pending accounts
/// only — a non-pending row is left untouched and the caller gets a Conflict ("log in instead"),
/// mirroring [`upsert_pending_user`]. No password/phone change.
pub async fn update_pending_user_role(
    db: &PgPool,
    user_id: Uuid,
    role: &str,
) -> Result<(), AppError> {
    let res = sqlx::query(
        r#"
        UPDATE identity.users
           SET role = $2::identity.user_role,
               updated_at = now()
         WHERE id = $1
           AND approval_status = 'pending'::identity.approval_status
        "#,
    )
    .bind(user_id)
    .bind(role)
    .execute(db)
    .await?;

    if res.rows_affected() == 0 {
        return Err(AppError::Conflict(
            "This account can no longer change role. Please log in instead.".to_string(),
        ));
    }
    Ok(())
}

/// Outcome of consuming a `user.approved` event.
#[derive(Debug, PartialEq, Eq)]
pub enum ApprovedOutcome {
    /// The account was flipped to `approved` (it can now log in).
    Applied,
    /// This `event_id` was already processed — a redelivery; no-op (idempotent).
    Duplicate,
    /// No such user (or already deleted). The event is still recorded as processed so it does
    /// not redeliver forever; logged by the caller.
    UserNotFound,
}

// ─────────────────────────────────────────────────────────────────────────────
// Multi-role (Option A: one phone = one account holding BOTH roles) — `user_roles`
// is the SET of APPROVED roles a user has. `users.role` stays as the registration/
// primary role for backward compat (every existing JWT carries it; login mints it).
// ─────────────────────────────────────────────────────────────────────────────

/// The set of APPROVED roles a user holds, ascending by enrolment time (the registration
/// role — backfilled — sorts first as the oldest). Used by `GET /auth/me` (`roles`) and
/// `POST /auth/login` (`available_roles`, so the app can show a role picker when >1).
///
/// BACKWARD COMPAT: a single-role user (every pre-migration account, backfilled by 0007)
/// returns exactly `[their_role]`, so the shape is identical to a single-role world.
pub async fn list_user_roles(db: &PgPool, user_id: Uuid) -> Result<Vec<String>, AppError> {
    let rows: Vec<(String,)> = sqlx::query_as(
        r#"
        SELECT role::text AS role
        FROM identity.user_roles
        WHERE user_id = $1
        ORDER BY created_at ASC, role ASC
        "#,
    )
    .bind(user_id)
    .fetch_all(db)
    .await?;
    Ok(rows.into_iter().map(|(r,)| r).collect())
}

/// THE security gate for `POST /auth/switch-role`: is `role` in the caller's APPROVED
/// `user_roles` set? A switch token is minted ONLY when this returns `true` — a role the
/// user is not enrolled in can never be switched to (no privilege escalation). A PK probe
/// on `(user_id, role)`. An unknown role string simply never matches (no row) → `false`.
pub async fn user_has_role(db: &PgPool, user_id: Uuid, role: &str) -> Result<bool, AppError> {
    let row: Option<(i32,)> = sqlx::query_as(
        r#"
        SELECT 1
        FROM identity.user_roles
        WHERE user_id = $1 AND role = $2::identity.user_role
        "#,
    )
    .bind(user_id)
    .bind(role)
    .fetch_optional(db)
    .await?;
    Ok(row.is_some())
}

/// Add `(user_id, role)` to `user_roles` IDEMPOTENTLY (`ON CONFLICT DO NOTHING`). Driven by
/// the `user.approved` event when a profile (the registration role OR a later second role)
/// is approved — that is the ONLY way a role enters the enrolled set. Returns `true` if a
/// NEW row was inserted (a freshly-enrolled role), `false` if it was already present
/// (redelivery / already enrolled). Caller must scope this to a live (non-deleted) user.
///
/// Generic over the SQLx executor so it runs BOTH standalone (`&PgPool`) AND inside the
/// approval transaction (`&mut *tx`) — the approval flip + this enrolment commit atomically,
/// with no duplicated INSERT SQL.
pub async fn add_user_role<'e, E>(executor: E, user_id: Uuid, role: &str) -> Result<bool, AppError>
where
    E: sqlx::Executor<'e, Database = sqlx::Postgres>,
{
    let res = sqlx::query(
        r#"
        INSERT INTO identity.user_roles (user_id, role)
        VALUES ($1, $2::identity.user_role)
        ON CONFLICT (user_id, role) DO NOTHING
        "#,
    )
    .bind(user_id)
    .bind(role)
    .execute(executor)
    .await?;
    Ok(res.rows_affected() == 1)
}

/// Re-read a live, ACTIVE user's `token_revocation_version` to mint a fresh token pair for a
/// role switch (`POST /auth/switch-role`). Unlike [`user_auth_meta`] this does NOT re-derive
/// the role from `users.role` — the switch target comes from the caller's enrolled set (checked
/// separately via [`user_has_role`]) — it only confirms the account is still live/active and
/// returns the current `trv`. `None` if the user is gone/deactivated (defense-in-depth: a token
/// is never minted for an erased account). Note `approval_status` is NOT re-checked here because
/// enrolment in `user_roles` already implies an approved profile for that role.
pub async fn user_trv_if_active(db: &PgPool, user_id: Uuid) -> Result<Option<i32>, AppError> {
    let row: Option<(i32,)> = sqlx::query_as(
        r#"
        SELECT token_revocation_version
        FROM identity.users
        WHERE id = $1 AND is_active = TRUE AND deleted_at IS NULL
        "#,
    )
    .bind(user_id)
    .fetch_optional(db)
    .await?;
    Ok(row.map(|(v,)| v))
}

/// Flip the user's OWN `approval_status` to `approved` AND enrol the approved `role` into
/// `user_roles`, driven by the `user.approved` event that profile emits on admin approval.
/// **Idempotent by `event_id`**: the claim into `processed_events` + the `users` update + the
/// `user_roles` upsert happen in ONE transaction, so a redelivered event (JetStream
/// at-least-once) is a safe no-op. This is identity writing its OWN schema — the event is the
/// only coupling to profile (no cross-schema write in either direction).
///
/// MULTI-ROLE (Option A): the `role` carried by the event is the role whose profile was just
/// approved — the registration role on a first approval, OR a SECOND role enrolled via
/// `POST /auth/roles`. Enrolling it here (`ON CONFLICT DO NOTHING`) is the ONLY path that adds
/// a role to the switchable set, so a role becomes usable strictly AFTER approval. The
/// `user_roles` insert is skipped on the UserNotFound path (a forged/stale event for a missing
/// user must not create a dangling role row).
#[tracing::instrument(skip(db), fields(event_id = %event_id, user_id = %user_id, role = %role))]
pub async fn approve_user_on_event(
    db: &PgPool,
    event_id: Uuid,
    event_type: &str,
    user_id: Uuid,
    role: &str,
) -> Result<ApprovedOutcome, AppError> {
    let mut tx = db.begin().await?;

    // 1) Claim the event_id — the idempotency anchor. A redelivery inserts nothing.
    let claim = sqlx::query(
        "INSERT INTO identity.processed_events (event_id, event_type) \
         VALUES ($1, $2) ON CONFLICT (event_id) DO NOTHING",
    )
    .bind(event_id)
    .bind(event_type)
    .execute(&mut *tx)
    .await?;
    if claim.rows_affected() == 0 {
        tx.rollback().await?;
        return Ok(ApprovedOutcome::Duplicate);
    }

    // 2) Flip approval_status. Only a live (not soft-deleted) account is approvable — so a
    //    stale/forged approval can never re-enable an erased account (login also re-checks
    //    is_active independently, defense-in-depth).
    let res = sqlx::query(
        "UPDATE identity.users \
         SET approval_status = 'approved'::identity.approval_status, updated_at = now() \
         WHERE id = $1 AND deleted_at IS NULL",
    )
    .bind(user_id)
    .execute(&mut *tx)
    .await?;

    // 3) Enrol the approved role into the switchable set (idempotent). ONLY for a live account
    //    that the flip matched — never for the UserNotFound path, so a forged/stale event can't
    //    seed a role for a missing/erased user. `ON CONFLICT DO NOTHING` absorbs a redelivery or
    //    an already-enrolled role (e.g. the backfilled registration role). A role string that
    //    is not a valid enum value would error the tx — but profile only ever emits guard/
    //    customer (the route determines it), so this is a defended-against impossibility.
    if res.rows_affected() == 1 {
        add_user_role(&mut *tx, user_id, role).await?;
    }

    // Commit the claim even when 0 rows matched (UserNotFound). This is deliberate: in the real
    // flow the identity row ALWAYS predates an approval (register → profile submit → admin
    // approve, each gated on the prior), so a 0-row match means a forged/stale/deleted-user
    // event — recording it (vs. rollback) prevents a bogus event from redelivering forever. The
    // caller logs UserNotFound loudly so a genuine anomaly is still visible.
    tx.commit().await?;

    if res.rows_affected() == 0 {
        Ok(ApprovedOutcome::UserNotFound)
    } else {
        Ok(ApprovedOutcome::Applied)
    }
}

/// Max concurrent live refresh families (≈ logged-in sessions) per user. A new login beyond
/// this evicts the least-recently-active family, so a login loop / token-minting abuse cannot
/// grow unbounded session state (the only other ceiling is natural 7-day expiry).
const MAX_SESSIONS_PER_USER: i64 = 5;

/// Device/IP/user-agent context captured onto a refresh-token row at login/refresh (#144
/// per-device sessions). All optional — a login without a captured UA/IP still works. `ip` is
/// stored raw (the sessions API may mask it on the way out).
#[derive(Debug, Default, Clone)]
pub struct DeviceContext {
    pub user_agent: Option<String>,
    pub ip: Option<String>,
}

/// Persist a freshly-issued refresh token (new family on login). Returns the opaque
/// token the client receives (`{rotation_id}.{secret}`). Enforces the per-user session cap
/// first (evict oldest beyond the cap). `device` stamps the login's UA/IP onto the family's
/// first row so the sessions list (#144) can show it.
pub async fn create_refresh_family(
    db: &PgPool,
    user_id: Uuid,
    device: &DeviceContext,
) -> Result<String, AppError> {
    enforce_session_cap(db, user_id).await?;
    let family_id = Uuid::new_v4();
    issue_refresh(db, user_id, family_id, device).await
}

/// Revoke the least-recently-active refresh families beyond `MAX_SESSIONS_PER_USER - 1`, so that
/// after the caller adds the new family the user ends at most at the cap. "Recency" is the
/// family's most recent rotation (`MAX(created_at)`), i.e. LRU eviction. (A rare concurrent-login
/// race may transiently leave cap+1 families; it self-corrects on the next login and is a
/// hardening control, not a hard invariant — so we don't pay for a serializing lock here.)
async fn enforce_session_cap(db: &PgPool, user_id: Uuid) -> Result<(), AppError> {
    let stale: Vec<(Uuid,)> = sqlx::query_as(
        r#"
        SELECT family_id FROM (
            SELECT family_id, MAX(created_at) AS last_active
            FROM identity.refresh_tokens
            WHERE user_id = $1 AND revoked = FALSE
            GROUP BY family_id
            ORDER BY last_active DESC
            OFFSET $2
        ) evictable
        "#,
    )
    .bind(user_id)
    .bind(MAX_SESSIONS_PER_USER - 1)
    .fetch_all(db)
    .await?;

    for (family_id,) in stale {
        revoke_family(db, family_id).await?;
    }
    Ok(())
}

/// Insert one refresh-token row in `family_id` and return its opaque token. Used for the
/// initial login token (rotation uses its own in-tx insert). Stamps the login `device` context
/// (UA/IP) + `last_used_at = now()` so the sessions list (#144) shows the device + freshness.
async fn issue_refresh(
    db: &PgPool,
    user_id: Uuid,
    family_id: Uuid,
    device: &DeviceContext,
) -> Result<String, AppError> {
    let rotation_id = Uuid::new_v4();
    let jti = Uuid::new_v4();
    let secret = Uuid::new_v4().to_string();
    let expires_at: DateTime<Utc> = Utc::now() + TimeDelta::days(REFRESH_TOKEN_DAYS);

    let secret_for_hash = secret.clone();
    let secret_hash = tokio::task::spawn_blocking(move || password::hash_secret(&secret_for_hash))
        .await
        .map_err(|e| AppError::Internal(format!("hash task failed: {e}")))??;

    sqlx::query(
        r#"
        INSERT INTO identity.refresh_tokens
            (user_id, family_id, rotation_id, jti, secret_hash, expires_at,
             user_agent, ip, last_used_at)
        VALUES ($1, $2, $3, $4, $5, $6, $7, $8, now())
        "#,
    )
    .bind(user_id)
    .bind(family_id)
    .bind(rotation_id)
    .bind(jti)
    .bind(&secret_hash)
    .bind(expires_at)
    .bind(device.user_agent.as_deref())
    .bind(device.ip.as_deref())
    .execute(db)
    .await?;

    Ok(crate::domain::token::assemble(rotation_id, &secret))
}

/// A refresh row located by its `rotation_id`, with everything the rotation decision +
/// secret check need.
pub struct LocatedRefresh {
    pub user_id: Uuid,
    pub family_id: Uuid,
    /// Rotation-decision inputs (revoked/expiry/family age) — the family-age ceiling now lives in
    /// `StoredRefresh::family_started_at` so `domain::rotation::decide` owns the whole decision.
    pub stored: StoredRefresh,
    secret_hash: String,
}

impl LocatedRefresh {
    /// Argon2-verify the presented secret against the stored hash (constant-time).
    pub async fn secret_matches(&self, secret: &str) -> Result<bool, AppError> {
        let secret = secret.to_string();
        let hash = self.secret_hash.clone();
        tokio::task::spawn_blocking(move || password::verify_secret(&secret, &hash))
            .await
            .map_err(|e| AppError::Internal(format!("verify task failed: {e}")))?
    }
}

/// Locate a refresh-token row by its public `rotation_id`.
// The row tuple gains a 6th column (family_started_at) for the absolute-rotation ceiling; the
// file consistently uses positional tuples for ad-hoc row reads, so allow the wider shape here.
#[allow(clippy::type_complexity)]
pub async fn find_refresh_by_rotation(
    db: &PgPool,
    rotation_id: Uuid,
) -> Result<Option<LocatedRefresh>, AppError> {
    let row: Option<(Uuid, Uuid, bool, DateTime<Utc>, DateTime<Utc>, String)> = sqlx::query_as(
        r#"
        SELECT rt.user_id, rt.family_id, rt.revoked, rt.expires_at,
               (SELECT MIN(created_at) FROM identity.refresh_tokens f
                WHERE f.family_id = rt.family_id) AS family_started_at,
               rt.secret_hash
        FROM identity.refresh_tokens rt
        WHERE rt.rotation_id = $1
        "#,
    )
    .bind(rotation_id)
    .fetch_optional(db)
    .await?;

    Ok(row.map(
        |(user_id, family_id, revoked, expires_at, family_started_at, secret_hash)| {
            LocatedRefresh {
                user_id,
                family_id,
                stored: StoredRefresh {
                    revoked,
                    expires_at,
                    family_started_at,
                },
                secret_hash,
            }
        },
    ))
}

/// Atomically revoke the presented rotation and mint its successor in the SAME family.
/// One transaction: prevents a window where the old token is dead but the new one is not
/// yet recorded (RFC 6749 §6 rotation).
///
/// Returns `Ok(None)` when the presented rotation was ALREADY revoked by the time the
/// conditional UPDATE ran — i.e. a concurrent refresh of the very same token (double-spend
/// race) won the row first. In that case we mint NO successor, so one refresh token can never
/// yield two live chains; the caller rejects the loser with 401.
pub async fn rotate(
    db: &PgPool,
    user_id: Uuid,
    family_id: Uuid,
    presented_rotation_id: Uuid,
    device: &DeviceContext,
) -> Result<Option<String>, AppError> {
    let mut tx = db.begin().await?;

    // Conditional revoke: only the FIRST rotation of this token flips revoked false→true and
    // affects a row. A concurrent second rotation sees 0 rows and must abort (no successor).
    let revoked = sqlx::query(
        "UPDATE identity.refresh_tokens SET revoked = TRUE WHERE rotation_id = $1 AND revoked = FALSE",
    )
    .bind(presented_rotation_id)
    .execute(&mut *tx)
    .await?;
    if revoked.rows_affected() == 0 {
        tx.rollback().await?;
        return Ok(None);
    }

    // Re-issue inside the family. We hash + insert here rather than calling `issue_refresh`
    // so the whole rotate stays in one tx. The successor inherits the family's device context
    // when the refresh carried none (a token refresh from the same device often omits the UA),
    // and stamps `last_used_at = now()` so the sessions list shows the family as fresh.
    let rotation_id = Uuid::new_v4();
    let jti = Uuid::new_v4();
    let secret = Uuid::new_v4().to_string();
    let expires_at: DateTime<Utc> = Utc::now() + TimeDelta::days(REFRESH_TOKEN_DAYS);
    let secret_for_hash = secret.clone();
    let secret_hash = tokio::task::spawn_blocking(move || password::hash_secret(&secret_for_hash))
        .await
        .map_err(|e| AppError::Internal(format!("hash task failed: {e}")))??;

    // Carry the family's existing UA/IP forward when this refresh didn't supply one (so the
    // session's device label doesn't blank out on a UA-less token refresh).
    let prior: Option<(Option<String>, Option<String>)> = sqlx::query_as(
        "SELECT user_agent, ip FROM identity.refresh_tokens \
         WHERE family_id = $1 ORDER BY created_at ASC LIMIT 1",
    )
    .bind(family_id)
    .fetch_optional(&mut *tx)
    .await?;
    let (prior_ua, prior_ip) = prior.unwrap_or((None, None));
    let ua = device.user_agent.clone().or(prior_ua);
    let ip = device.ip.clone().or(prior_ip);

    sqlx::query(
        r#"
        INSERT INTO identity.refresh_tokens
            (user_id, family_id, rotation_id, jti, secret_hash, expires_at,
             user_agent, ip, last_used_at)
        VALUES ($1, $2, $3, $4, $5, $6, $7, $8, now())
        "#,
    )
    .bind(user_id)
    .bind(family_id)
    .bind(rotation_id)
    .bind(jti)
    .bind(&secret_hash)
    .bind(expires_at)
    .bind(ua.as_deref())
    .bind(ip.as_deref())
    .execute(&mut *tx)
    .await?;

    tx.commit().await?;

    Ok(Some(crate::domain::token::assemble(rotation_id, &secret)))
}

/// Revoke every token in a family (logout, or reuse-detection kill-switch).
pub async fn revoke_family(db: &PgPool, family_id: Uuid) -> Result<u64, AppError> {
    let res = sqlx::query(
        "UPDATE identity.refresh_tokens SET revoked = TRUE WHERE family_id = $1 AND revoked = FALSE",
    )
    .bind(family_id)
    .execute(db)
    .await?;
    Ok(res.rows_affected())
}

