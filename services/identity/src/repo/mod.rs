/// The `(role, display_name, email)` row both self-profile reads return — named so the read +
/// update share one shape (and to satisfy clippy's type-complexity lint on the update's Result).
type SelfProfileRow = (String, Option<String>, Option<String>);

/// The caller's own self-profile fields for `GET /auth/me` (their own data → un-redacted).
/// `display_name`/`email` are nullable (an admin may not have filled them; a customer/guard
/// never sets email here). `None` (NotFound) when the row is gone/soft-deleted.
#[derive(Debug)]
pub struct SelfProfile {
    pub role: String,
    pub display_name: Option<String>,
    pub email: Option<String>,
}

/// Read the caller's own `{ role, display_name, email }` for `GET /auth/me`. Scoped strictly to
/// `user_id`; a soft-deleted row is treated as absent so an erased account never surfaces a name.
pub async fn self_profile(db: &PgPool, user_id: Uuid) -> Result<SelfProfile, AppError> {
    let row: Option<SelfProfileRow> = sqlx::query_as(
        r#"
        SELECT role::text AS role, display_name, email
        FROM identity.users
        WHERE id = $1 AND deleted_at IS NULL
        "#,
    )
    .bind(user_id)
    .fetch_optional(db)
    .await?;
    let (role, display_name, email) =
        row.ok_or_else(|| AppError::NotFound("User not found".to_string()))?;
    Ok(SelfProfile {
        role,
        display_name,
        email,
    })
}

/// Update the CALLER'S OWN `display_name` + `email` (`PUT /auth/me`). Self-only — `user_id` is the
/// authenticated caller, and phone/role/password are NEVER touched here. Both args are already
/// trimmed + validated (display_name 1..=120; email lowercased + shape-checked) by the handler.
/// `email` is stored as `Some(lowercased)` or `None` (cleared). A `email` collision with another
/// user trips the `UNIQUE(email)` constraint (23505) → [`AppError::ConflictCode`] with code
/// `EMAIL_TAKEN`, so the handler returns a 409 the client can branch on. Soft-deleted rows are
/// excluded (an erased account cannot be edited). Returns the refreshed self-profile.
pub async fn update_self_profile(
    db: &PgPool,
    user_id: Uuid,
    display_name: &str,
    email: Option<&str>,
) -> Result<SelfProfile, AppError> {
    let row: Result<Option<SelfProfileRow>, sqlx::Error> = sqlx::query_as(
        r#"
        UPDATE identity.users
        SET display_name = $2, email = $3, updated_at = now()
        WHERE id = $1 AND deleted_at IS NULL
        RETURNING role::text AS role, display_name, email
        "#,
    )
    .bind(user_id)
    .bind(display_name)
    .bind(email)
    .fetch_optional(db)
    .await;

    let row = match row {
        Ok(r) => r,
        // 23505 on the only UNIQUE column we write here (email) → another account already holds it.
        Err(sqlx::Error::Database(d)) if d.code().as_deref() == Some("23505") => {
            return Err(AppError::ConflictCode {
                code: "EMAIL_TAKEN",
                message: "That email address is already in use.".to_string(),
            });
        }
        Err(e) => return Err(e.into()),
    };

    let (role, display_name, email) =
        row.ok_or_else(|| AppError::NotFound("User not found".to_string()))?;
    Ok(SelfProfile {
        role,
        display_name,
        email,
    })
}

/// Change the caller's OWN password (`PUT /auth/password`): verify `current_password` against the
/// stored Argon2 hash (constant-time), then Argon2-hash `new_pin_hash` and store it — all so the
/// new hash is only written when the current one verifies. The two client-supplied values are
/// SHA-256 hex digests (same shape as login's `password`), Argon2'd here like register's pin_hash.
/// On a wrong current password returns a GENERIC 401 (no enumeration, mirrors login). Returns the
/// new `token_revocation_version` to bump so the caller can force-revoke the user's OTHER sessions
/// (the handler revokes the refresh families + publishes the Redis marker). Soft-deleted rows are
/// excluded. `skip(db, current_password, new_pin_hash)`: never log either secret.
#[tracing::instrument(skip(db, current_password, new_pin_hash), fields(user_id = %user_id))]
pub async fn change_password(
    db: &PgPool,
    user_id: Uuid,
    current_password: &str,
    new_pin_hash: &str,
) -> Result<i32, AppError> {
    let mut tx = db.begin().await?;

    // Lock the row + read the current hash + revocation version under the tx.
    let row: Option<(String, i32)> = sqlx::query_as(
        "SELECT password_hash, token_revocation_version FROM identity.users \
         WHERE id = $1 AND deleted_at IS NULL FOR UPDATE",
    )
    .bind(user_id)
    .fetch_optional(&mut *tx)
    .await?;
    let (current_hash, current_version) = match row {
        Some(r) => r,
        None => {
            tx.rollback().await?;
            return Err(AppError::NotFound("User not found".to_string()));
        }
    };

    // Verify the presented current password (Argon2, constant-time, off-runtime).
    let presented = current_password.to_string();
    let ok =
        tokio::task::spawn_blocking(move || password::verify_secret(&presented, &current_hash))
            .await
            .map_err(|e| AppError::Internal(format!("verify task failed: {e}")))??;
    if !ok {
        tx.rollback().await?;
        // Generic 401 — same as login; never reveal whether the account/current password matched.
        return Err(AppError::Unauthorized("Invalid credentials".to_string()));
    }

    // Hash the new pin_hash (CPU-bound → spawn_blocking) and store it. Bump the revocation version
    // in the SAME write so the other-sessions kill below is consistent with the new credential.
    let new_pin = new_pin_hash.to_string();
    let new_hash = tokio::task::spawn_blocking(move || password::hash_secret(&new_pin))
        .await
        .map_err(|e| AppError::Internal(format!("hash task failed: {e}")))??;
    let new_version = revocation::next_revocation_version(current_version);

    sqlx::query(
        "UPDATE identity.users \
         SET password_hash = $2, token_revocation_version = $3, updated_at = now() \
         WHERE id = $1",
    )
    .bind(user_id)
    .bind(&new_hash)
    .bind(new_version)
    .execute(&mut *tx)
    .await?;

    // Revoke every outstanding refresh family — the caller's OTHER sessions can no longer rotate.
    sqlx::query(
        "UPDATE identity.refresh_tokens SET revoked = TRUE WHERE user_id = $1 AND revoked = FALSE",
    )
    .bind(user_id)
    .execute(&mut *tx)
    .await?;

    // Audit the credential change in the SAME tx — a change_password either happens WITH its
    // audit row or not at all (parity with reset_password_by_phone; security-review follow-up).
    record_credential_event(&mut tx, user_id, "password_changed", None).await?;

    tx.commit().await?;
    tracing::info!(
        new_version,
        "password changed (other sessions force-revoked)"
    );
    Ok(new_version)
}

/// Cheap existence probe: does a LIVE (active, non-deleted) account hold this phone?
/// Used by `/auth/reset-pin` BEFORE it burns the single-use token jti — a reset attempt
/// against a phone with no resettable account should fail WITHOUT consuming the token
/// (otherwise a deactivated-account user burns a full OTP round per attempt). Purely
/// advisory: the authoritative row lock + re-check still happens inside
/// [`reset_password_by_phone`]'s transaction.
pub async fn active_account_exists_by_phone(db: &PgPool, phone: &str) -> Result<bool, AppError> {
    let row: Option<(i32,)> = sqlx::query_as(
        "SELECT 1 FROM identity.users \
         WHERE phone = $1 AND is_active = TRUE AND deleted_at IS NULL",
    )
    .bind(phone)
    .fetch_optional(db)
    .await?;
    Ok(row.is_some())
}

/// Reset the PIN of an EXISTING account BY PHONE — the "forgot PIN" flow, driven by a verified OTP
/// token (the phone comes from that token, NEVER the request body). No current-PIN verify: phone
/// ownership + the single-use token ARE the authorization. Stores the new Argon2 hash, bumps the
/// revocation version, and revokes ALL refresh families in ONE tx — so a reset kills EVERY existing
/// session (exactly like [`change_password`], minus the current-password check). Returns
/// `(user_id, new_revocation_version)`, or `None` when no ACTIVE (non-deleted) account holds the
/// phone — the caller maps `None` to a generic error (the OTP token already gates enumeration).
pub async fn reset_password_by_phone(
    db: &PgPool,
    phone: &str,
    new_pin_hash: &str,
) -> Result<Option<(Uuid, i32)>, AppError> {
    let mut tx = db.begin().await?;

    // Lock the row + read the current revocation version. Only a live (active, non-deleted) account
    // is resettable — a deactivated/erased account can never be re-credentialed by a stray token.
    let row: Option<(Uuid, i32)> = sqlx::query_as(
        "SELECT id, token_revocation_version FROM identity.users \
         WHERE phone = $1 AND is_active = TRUE AND deleted_at IS NULL FOR UPDATE",
    )
    .bind(phone)
    .fetch_optional(&mut *tx)
    .await?;
    let (user_id, current_version) = match row {
        Some(r) => r,
        None => {
            tx.rollback().await?;
            return Ok(None);
        }
    };

    // Hash the new pin_hash (CPU-bound → spawn_blocking) and store it, bumping the revocation version
    // in the SAME write so the session kill below is consistent with the new credential.
    let new_pin = new_pin_hash.to_string();
    let new_hash = tokio::task::spawn_blocking(move || password::hash_secret(&new_pin))
        .await
        .map_err(|e| AppError::Internal(format!("hash task failed: {e}")))??;
    let new_version = revocation::next_revocation_version(current_version);

    sqlx::query(
        "UPDATE identity.users \
         SET password_hash = $2, token_revocation_version = $3, updated_at = now() \
         WHERE id = $1",
    )
    .bind(user_id)
    .bind(&new_hash)
    .bind(new_version)
    .execute(&mut *tx)
    .await?;

    // Revoke EVERY outstanding refresh family — a forgotten-PIN reset invalidates all prior sessions.
    sqlx::query(
        "UPDATE identity.refresh_tokens SET revoked = TRUE WHERE user_id = $1 AND revoked = FALSE",
    )
    .bind(user_id)
    .execute(&mut *tx)
    .await?;

    // Audit the reset in the SAME tx (actor = the account itself — the reset is authorized by
    // phone ownership, there is no separate caller identity). `via_otp` records the channel.
    record_credential_event(&mut tx, user_id, "pin_reset", Some("via_otp")).await?;

    tx.commit().await?;
    tracing::info!(
        new_version,
        "pin reset by phone (all sessions force-revoked)"
    );
    Ok(Some((user_id, new_version)))
}

/// Append a row to `identity.credential_audit` INSIDE the caller's transaction — credential
/// changes (`password_changed`, `pin_reset`) commit atomically with their audit trail (PDPA
/// parity with profile's `access_audit`; the table is append-only, nothing here updates it).
async fn record_credential_event(
    tx: &mut sqlx::Transaction<'_, sqlx::Postgres>,
    user_id: Uuid,
    action: &str,
    detail: Option<&str>,
) -> Result<(), AppError> {
    sqlx::query(
        "INSERT INTO identity.credential_audit (user_id, action, detail) VALUES ($1, $2, $3)",
    )
    .bind(user_id)
    .bind(action)
    .bind(detail)
    .execute(&mut **tx)
    .await?;
    Ok(())
}

